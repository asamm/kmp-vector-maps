"""
Runs both Mapsforge goldens against an upstream tag built from source, for tags without published
jars (docs/upstream.md, "Following upstream"). Equal reader and theme-callback dumps, and label-free
tiles within the accepted differences (D37), mean the vendored render matches that release; the label
goldens are our own and do not depend on the tag.

Steps, all outside the repo and outside ~/.m2:
  1. shallow-clones the tag into a temporary folder (long paths on, as upstream's exceed 260) and
     prints its commit, to check against the sync log;
  2. builds mapsforge-core, -map, -map-reader, -map-awt and -map-android into a local Maven folder,
     with ANDROID_HOME taken from local.properties, without a Gradle daemon;
  3. runs :dev:mapsforge:golden:test and :dev:mapsforge:golden-android:test with an init script
     that swaps the JitPack jars for those, every task re-run.

Usage: python dev/mapsforge/upstream/verify_upstream.py <tag> [--keep]
"""

import os
import pathlib
import re
import shutil
import stat
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[3]
MODULES = ["mapsforge-core", "mapsforge-map", "mapsforge-map-reader", "mapsforge-map-awt", "mapsforge-map-android"]
GRADLEW = "gradlew.bat" if os.name == "nt" else "gradlew"
INIT_SCRIPT = """// generated by verify_upstream.py: upstream {tag} from source in place of the JitPack jars
beforeSettings {{ settings ->
    settings.dependencyResolutionManagement.repositories.maven {{ url = uri("{repo}") }}
}}
allprojects {{
    configurations.all {{
        resolutionStrategy.eachDependency {{ details ->
            if (details.requested.group == "com.github.mapsforge.mapsforge") {{
                details.useTarget("org.mapsforge:${{details.requested.name}}:master-SNAPSHOT")
                details.because('upstream {tag} from source')
            }}
        }}
    }}
}}
"""


def android_home():
    for line in (ROOT / "local.properties").read_text(encoding="utf-8").splitlines():
        key, _, value = line.partition("=")
        if key.strip() == "sdk.dir":
            return value.strip().replace("\\:", ":").replace("\\\\", "/")
    sys.exit("verify_upstream.py: no sdk.dir in local.properties")


def run(args, cwd, env=None):
    print("$", " ".join(args))
    subprocess.run(args, cwd=cwd, env=env, check=True)


def remove(work):
    # git writes its packs read-only, which Windows refuses to delete
    def writable(function, path, _):
        os.chmod(path, stat.S_IWRITE)
        function(path)

    shutil.rmtree(work, onexc=writable)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    tag = sys.argv[1]
    if not re.fullmatch(r"[A-Za-z0-9._-]+", tag):
        sys.exit(f"verify_upstream.py: not a tag name: {tag}")
    sdk = android_home()
    work = pathlib.Path(tempfile.mkdtemp(prefix="mf-"))
    try:
        source = work / "src"
        repo = work / "m2"
        run(["git", "-c", "core.longpaths=true", "-c", "advice.detachedHead=false", "clone", "-q", "--depth", "1",
             "--branch", tag, "https://github.com/mapsforge/mapsforge.git", str(source)], cwd=work)
        run(["git", "-C", str(source), "log", "-1", "--format=commit %H"], cwd=work)
        (source / "local.properties").write_text(f"sdk.dir={sdk}\n", encoding="utf-8")
        env = dict(os.environ, ANDROID_HOME=sdk)
        tasks = [f":{m}:publishToMavenLocal" for m in MODULES]
        run([str(source / GRADLEW), *tasks, f"-Dmaven.repo.local={repo.as_posix()}", "-x", "javadoc", "-q",
             "--no-daemon"], cwd=source, env=env)
        init = work / "use-upstream.gradle"
        init.write_text(INIT_SCRIPT.format(tag=tag, repo=repo.as_posix()), encoding="utf-8")
        run([str(ROOT / GRADLEW), "--init-script", str(init), ":dev:mapsforge:golden:test",
             ":dev:mapsforge:golden-android:test", "--rerun-tasks"], cwd=ROOT)
        print(f"\nverify_upstream.py: the vendored render matches upstream {tag}")
    finally:
        if "--keep" in sys.argv:
            print(f"kept {work}")
        else:
            remove(work)


if __name__ == "__main__":
    main()
